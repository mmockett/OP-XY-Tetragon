#!/usr/bin/env python3
"""Writes syahi/tables.h: the fixed-point tables the engine and screen read.

    python3 syahi/tools/make_tables.py

Every table is a formula evaluated here (a sine, 2^x, a contact's roll-off,
tanh, filter coefficients); nothing is sampled from another instrument.
"""
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parent.parent
SR = 44100.0

# Filter classes: the Q of each state-variable filter the voice runs.
Q_CLASSES = [("butter", 0.7071), ("wires", 0.8), ("tone", 0.9), ("clap", 1.4), ("ring", 5.0), ("drum", 6.0)]
FC_LOW = 16.0          # Hz, the grid's first cutoff
FC_STEPS = 88          # eighths of an octave
FC_TOP = 0.46 * SR     # cutoffs above this are clamped


def q31(x):
    return max(-2147483648, min(2147483647, int(round(x * 2147483648.0))))


def rows(values, per=8):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per]) + ",")
    return "\n".join(out)


def main():
    parts = ["#pragma once",
             "// Generated by tools/make_tables.py: edit the generator, then regenerate.",
             "#include <opxy/types.hpp>",
             "",
             "namespace syahi {",
             "namespace tables {",
             "using opxy::i16;",
             "using opxy::i32;"]
    # A sine of 2048 steps and one more for the wrap, 16 bits: 4 KiB, small
    # enough to stay in the data cache with sixteen voices' state (the module
    # runs from SDRAM; 32 KiB missed on most of the modes' reads).
    sine = [int(round(32767 * math.sin(2 * math.pi * i / 2048))) for i in range(2049)]
    parts += ["// sin(2 pi i / 2048) * 32767, and its first step again for the wrap.", "const i16 sine[2049] = {", rows(sine, 16), "};"]
    # 2^(i / 256), Q30.
    exp2 = [int(round(2 ** (i / 256) * (1 << 30))) for i in range(257)]
    exp2[-1] = min(exp2[-1], 2147483647)
    parts += ["// 2^(i / 256) in Q30.", "const i32 exp2[257] = {", rows(exp2), "};"]
    # A contact's roll-off: 1 / sqrt(1 + (2 f tau)^4) for log2(2 f tau) = (i - 128) / 16.
    mallet = [q31(min(0.9999999, 1 / math.sqrt(1 + 2 ** (4 * (i - 128) / 16)))) for i in range(257)]
    parts += ["// A soft contact's weight on a mode, 1 / sqrt(1 + (2 f tau)^4), at",
              "// log2(2 f tau) = (i - 128) / 16 octaves, Q31.", "const i32 mallet[257] = {", rows(mallet), "};"]
    # log2(1 + i / 256), Q16.
    log2 = [int(round(math.log2(1 + i / 256) * 65536)) for i in range(257)]
    parts += ["// log2(1 + i / 256) in Q16.", "const i32 log2[257] = {", rows(log2), "};"]
    # tanh(i / 64), Q31, for the drive.
    tanh = [q31(min(0.9999999, math.tanh(i / 64))) for i in range(257)]
    parts += ["// tanh(i / 64) in Q31: GRIT's drive.", "const i32 tanh[257] = {", rows(tanh), "};"]
    # GRIT's drive: 1 / tanh(1 + 0.45 g) for g = 1..15, Q28, and its input gain (1 + 0.45 g), Q24.
    makeup = [0] + [int(round((1 << 28) / math.tanh(1 + 0.45 * g))) for g in range(1, 16)]
    drive = [0] + [int(round((1 << 24) * (1 + 0.45 * g))) for g in range(1, 16)]
    parts += ["// GRIT 1..15: the drive's gain (Q24) and its make-up 1 / tanh(gain) (Q28).",
              "const i32 grit_drive[16] = {" + ", ".join(map(str, drive)) + "};",
              "const i32 grit_makeup[16] = {" + ", ".join(map(str, makeup)) + "};"]
    # GRIT below 0: a one-pole low-pass at 16 kHz * (1200 / 16000)^(-g / 16), coefficient Q31.
    soft = [q31(1 - math.exp(-2 * math.pi * 16000 * (1200 / 16000) ** (g / 16) / SR)) for g in range(17)]
    parts += ["// GRIT -1..-16 (index 1..16): the softening one-pole's coefficient, Q31.",
              "const i32 grit_soft[17] = {" + ", ".join(map(str, soft)) + "};"]
    # State-variable filter coefficients (Zavalishin's topology-preserving form).
    parts += ["// State-variable filters: a1, a2, a3 (Q31) for cutoffs FC_LOW * 2^(i / 8) Hz,",
              "// one table per Q, and each Q's k / 2 (Q31).",
              f"const i32 fc_steps = {FC_STEPS};",
              f"const i32 q_classes = {len(Q_CLASSES)};",
              "const i32 svf_k[q_classes] = {" + ", ".join(str(q31(0.5 / q)) for _, q in Q_CLASSES) + "};",
              "const i32 svf[q_classes][fc_steps][3] = {"]
    for name, q in Q_CLASSES:
        k = 1 / q
        entries = []
        for i in range(FC_STEPS):
            fc = min(FC_TOP, FC_LOW * 2 ** (i / 8))
            g = math.tan(math.pi * fc / SR)
            a1 = 1 / (1 + g * (g + k))
            a2 = g * a1
            a3 = g * a2
            entries.append("{%d, %d, %d}" % (q31(min(a1, 0.9999999)), q31(a2), q31(min(a3, 0.9999999))))
        parts.append(f"    {{  // {name}, Q {q}")
        for i in range(0, len(entries), 4):
            parts.append("        " + ", ".join(entries[i:i + 4]) + ",")
        parts.append("    },")
    parts += ["};"]
    # GRIT past +9: the 24 Hz high-pass's coefficient for a whole hold of
    # 3, 5, .. 13 samples, 1 - (1 - c)^hold, in the engine's Q31 arithmetic
    # (multiply truncates; power squares), so it matches it bit for bit.
    def mul(a, b):
        return min(0x7fffffff, (a * b) >> 31)
    def power(x, n):
        r = 0x7fffffff
        while n:
            if n & 1:
                r = mul(r, x)
            x = mul(x, x)
            n >>= 1
        return r
    crush_hp = [0x7fffffff - power(0x7fffffff - 7323000, 1 + 2 * (g - 9)) for g in range(10, 16)]
    parts += ["// GRIT +10..+15 (index 0..5): the 24 Hz high-pass over a hold of 3..13 samples, Q31.",
              "const i32 crush_hp[6] = {" + ", ".join(map(str, crush_hp)) + "};"]
    parts += ["}", "}", ""]
    (HERE / "tables.h").write_text("\n".join(parts))
    print("wrote", HERE / "tables.h")


if __name__ == "__main__":
    main()
