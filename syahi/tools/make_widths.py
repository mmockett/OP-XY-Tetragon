#!/usr/bin/env python3
"""Writes tests/widths.h: each printable ASCII character's advance in the
OP-XY's screen face (Univers Next Pro Light), thousandths of an em, for the
caption checks in tests/screen.cpp. The device lays text out by advance,
without kerning.

    XY_FONT=<UniversNextPro-Light.ttf> python3 tools/make_widths.py

The ruler is the suite's tools/caption_width.py.
"""
import os, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT.parent / "tools"))
import caption_width as cw  # noqa: E402  (reads XY_FONT)

widths = [round(cw.width(chr(c), 1000)) for c in range(32, 127)]
out = ["#pragma once", "// Generated by tools/make_widths.py from the OP-XY's screen face: advances of",
       "// ASCII 32..126 in thousandths of an em.", "const int advances[95] = {"]
for i in range(0, 95, 16):
    out.append("    " + ", ".join(map(str, widths[i:i + 16])) + ",")
out.append("};")
(ROOT / "tests" / "widths.h").write_text("\n".join(out) + "\n")
print("wrote tests/widths.h")
