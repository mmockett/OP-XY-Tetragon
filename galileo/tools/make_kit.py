#!/usr/bin/env python3
"""Writes GALILEO's generated headers from tools/catalog.py:

    python3 tools/make_kit.py

- kit.h: the models, their labels and groups, each key's default model and
  controls, and each model's output gain (tools/levels.json, written by
  tools/calibrate.py);
- tables.h: the fixed-point tables the engine and the screen share (sine,
  2^x, decay per sample, tanh, log2) and the motion tables (the handful's
  size, restitution, the balls' spacing).

Everything is computed here from formulas.
"""
import json
import math
import re
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import catalog  # noqa: E402

SR = 44100


def q(x, bits):
    return int(round(x * (1 << bits)))


def rows(values, per=8, fmt="{}"):
    out = []
    for i in range(0, len(values), per):
        out.append("    " + ", ".join(fmt.format(v) for v in values[i:i + per]) + ",")
    return "\n".join(out)


def tables():
    """tables.h declares the tables, tables.cpp defines them once (machine.json
    sources), so the engine's and the screen's translation units share one copy."""
    sine = [min(0x7fffffff, q(math.sin(2 * math.pi * i / 512), 31)) for i in range(513)]
    exp2 = [q(2 ** (i / 256), 30) for i in range(257)]                 # Q30, 2^30 .. 2^31
    decay = [min(0x7fffffff, q(math.exp(-2 ** (-i / 16)), 31)) for i in range(353)]
    tanh = [min(0x7fffffff, q(math.tanh(4 * i / 256), 31)) for i in range(257)]
    log2 = [q(math.log2(1 + i / 256), 16) for i in range(257)]
    # The handful: 1 + round(b^1.6 * 23) balls for the control b (0..127).
    count = [1 + int(round((b / 127) ** 1.6 * 23)) for b in range(128)]
    # Restitution 0.93 * b^0.5, Q15: the first touch already gives a rebound you hear.
    rest = [q(0.93 * (b / 127) ** 0.5, 15) for b in range(128)]
    # A handful of m: the balls' spacing and scatter, in samples, and how far
    # their weights are random (Q15). Two balls are a flam 23 ms apart; the
    # handful spreads over 23 ms (m - 1)^0.55, so 24 balls are a 130 ms shower.
    spacing = [0] * 25
    scatter = [0] * 25
    loose = [0] * 25
    for m in range(2, 25):
        spacing[m] = int(round(0.023 * (m - 1) ** 0.55 / (m - 1) * SR))
        scatter[m] = int(round(0.6 * spacing[m])) if m > 2 else int(round(0.003 * SR))
        loose[m] = q(min(1.0, max(0.0, (m - 3) / 5)), 15)
    # 1/m, Q16, for m 0..24 (0 unused).
    recip = [0] + [q(1 / m, 16) for m in range(1, 25)]
    # log2(i), Q16, for i 0..16 (0 unused): fret positions.
    log2i = [0] + [q(math.log2(i), 16) for i in range(1, 17)]
    # Pentatonic steps (minor), semitones in Q16 octaves: TINE's runs.
    penta = [q(s / 12, 16) for s in (0, 3, 5, 7, 10)]
    out = f"""// Generated by tools/make_kit.py: fixed-point tables, all from formulas.
#include "tables.h"

namespace galileo {{
using opxy::i32;
using opxy::u32;
using opxy::u16;
namespace table {{
// sin(2 pi i / 512), Q31: interpolated, its error is under -100 dB.
extern const i32 sine[513] = {{
{rows(sine)}
}};
// 2^(i / 256), Q30.
extern const u32 exp2[257] = {{
{rows(exp2)}
}};
// exp(-2^(-i / 16)), Q31: the per-sample decay for a time constant of 2^(i/16) samples.
extern const i32 decay[353] = {{
{rows(decay)}
}};
// tanh(4 i / 256), Q31.
extern const i32 tanh[257] = {{
{rows(tanh)}
}};
// log2(1 + i / 256), Q16.
extern const u32 log2[257] = {{
{rows(log2)}
}};
// The handful's size for each balls value.
extern const u8 ball_count[128] = {{
{rows(count, 16)}
}};
// Restitution for each bounce value, Q15.
extern const u16 restitution[128] = {{
{rows(rest, 16)}
}};
// A handful of m: the spacing and scatter of its balls (samples), and how much
// of each ball's weight is random (Q15).
extern const u16 ball_spacing[25] = {{
{rows(spacing, 13)}
}};
extern const u16 ball_scatter[25] = {{
{rows(scatter, 13)}
}};
extern const u16 ball_loose[25] = {{
{rows(loose, 13)}
}};
// 1/m, Q16.
extern const u32 reciprocal[25] = {{
{rows(recip, 13)}
}};
// log2(i), Q16.
extern const i32 log2_whole[17] = {{
{rows(log2i, 17)}
}};
// A minor pentatonic scale's steps, in Q16 octaves.
extern const i32 pentatonic[5] = {{{", ".join(map(str, penta))}}};
}}
}}
"""
    decls = re.findall(r"extern const (\w+) (\w+)\[(\d+)\]", out)
    header = ["#pragma once", "// Generated by tools/make_kit.py: the fixed-point tables (tables.cpp).",
              "#include <opxy/types.hpp>", "", "namespace galileo {", "namespace table {",
              "using opxy::i32;", "using opxy::u32;", "using opxy::u16;", "using opxy::u8;"]
    header += [f"extern const {t} {n}[{c}];" for t, n, c in decls]
    header += ["}", "}", ""]
    return "\n".join(header), out


def kit():
    levels_path = HERE / "levels.json"
    levels = json.loads(levels_path.read_text()) if levels_path.exists() else {}
    models = catalog.MODELS
    lines = []
    lines.append("#pragma once")
    lines.append("// Generated by tools/make_kit.py from tools/catalog.py: edit the catalog, then")
    lines.append("// regenerate. The engine and the screen both read these tables.")
    lines.append("#include <opxy/types.hpp>")
    lines.append("")
    lines.append("namespace galileo {")
    lines.append("namespace kit {")
    lines.append("using opxy::u32;")
    lines.append("using opxy::i32;")
    lines.append(f"const u32 models = {len(models)};")
    lines.append("const u32 keys = 24;")
    lines.append("enum Model : u32 { " + ", ".join(f"{m[0].lower()}" for m in models) + " };")
    lines.append("// A model: its name, its group, and its eight controls' labels: the body's")
    lines.append("// four, then the motion's four, the same on every model.")
    lines.append("struct Entry { const char* name; u32 group; const char* labels[8]; };")
    lines.append("const Entry model[models] = {")
    for name, group, labels, _snd, _mot in models:
        g = [gname for gname, _ in catalog.GROUPS].index(group)
        labs = ", ".join(f'"{x}"' for x in labels + catalog.MOTION)
        lines.append(f'    {{"{catalog.SHOWN.get(name, name.lower())}", {g}, {{{labs}}}}},')
    lines.append("};")
    lines.append(f"const u32 group_count = {len(catalog.GROUPS)};")
    lines.append("const char* const groups[group_count] = {" + ", ".join(f'"{g}"' for g, _ in catalog.GROUPS) + "};")
    lines.append("// Each model's output gain, Q26 (tools/calibrate.py): its default key sounds at its")
    lines.append("// role's loudness (tools/catalog.py TARGET).")
    gains = [int(levels.get(m[0], 1 << 26)) for m in models]
    lines.append("const i32 gain[models] = {" + ", ".join(map(str, gains)) + "};")
    trims_path = HERE / "trims.json"
    trims = json.loads(trims_path.read_text()) if trims_path.exists() else {}
    lines.append("// Each body control's loudness trim (tools/calibrate.py), log2 in 1/32 octave at the")
    lines.append("// control's 0, 32, 64, 96 and 127, the others at their defaults; 0 at its default.")
    lines.append("const signed char trim[models][4][5] = {")
    for m in models:
        t = trims.get(m[0], [[0] * 5] * 4)
        lines.append("    {" + ", ".join("{" + ", ".join(str(int(v)) for v in row) + "}" for row in t) + "},   // " + m[0])
    lines.append("};")
    lines.append("// Each key's model and eight controls, 0..127 (keys 53..76): the default kit.")
    lines.append("const unsigned char key_model[keys] = {" + ", ".join(str(catalog.model_index(k[0])) for k in catalog.DEFAULT_KIT) + "};")
    lines.append("const unsigned char key_values[keys][8] = {")
    for i, (m, values) in enumerate(catalog.DEFAULT_KIT):
        lines.append(f"    {{{', '.join(map(str, values))}}},   // {53 + i} {m}")
    lines.append("};")
    lines.append("// A key's stored controls as the SDK hands them to render (Q31).")
    lines.append("inline void key_controls(u32 key, i32* values) {")
    lines.append("    for (u32 c = 0; c < 8; ++c) values[c] = key_values[key][c] >= 127 ? 0x7fffffff : static_cast<i32>(static_cast<u32>(key_values[key][c]) << 24);")
    lines.append("}")
    lines.append("}")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    header, source = tables()
    (ROOT / "tables.h").write_text(header)
    # The definitions live in tables_data.h so a host tool can include them
    # whole; tables.cpp is their one home in a build.
    (ROOT / "tables_data.h").write_text(source.replace("// Generated by tools/make_kit.py: fixed-point tables, all from formulas.",
                                                       "// Generated by tools/make_kit.py: the tables' definitions, included once by tables.cpp."))
    (ROOT / "tables.cpp").write_text("// Generated by tools/make_kit.py: the fixed-point tables, defined once (tables_data.h).\n#include \"tables_data.h\"\n")
    (ROOT / "kit.h").write_text(kit())
    print("wrote tables.h, tables.cpp, kit.h")
