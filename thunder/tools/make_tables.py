#!/usr/bin/env python3
"""Writes thunder/tables.h: the fixed-point tables the engine reads.

    python3 thunder/tools/make_tables.py

Everything here is computed from first principles: powers of two, a sine, and
the modes of a thin rectangular sheet under tension and stiffness. Nothing is
sampled or copied from any instrument.

The sheet's modes: a rectangle of aspect 1.7 whose restoring force is part
tension (a membrane, f^2 ~ k^2) and part bending stiffness (a plate,
f^2 ~ k^4). Mode (m, n) has wavenumber k^2 = (m / 1.7)^2 + n^2. For each of 33
tensions from 0 (a slack, stiff plate) to 1 (a drumhead), the table holds the
eight lowest modes: their frequency over the (1, 1) mode's, as log2 in Q12,
and m and n, which give the mode's shape sin(m pi x) sin(n pi y) at the
strike point.
"""
import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parent.parent / "tables.h"
ASPECT = 1.7
TENSIONS = 33


def sheet_modes(tension):
    cands = []
    for m in range(1, 9):
        for n in range(1, 7):
            k2 = (m / ASPECT) ** 2 + n ** 2
            cands.append((k2, m, n))
    k2_11 = (1 / ASPECT) ** 2 + 1
    T = tension + 1e-3
    D = 1.0 - tension
    out = []
    for k2, m, n in cands:
        r = math.sqrt((T * k2 + D * k2 * k2 / k2_11) / (T * k2_11 + D * k2_11))
        out.append((r, m, n))
    out.sort()
    return out[:8]


def main():
    lines = ["#pragma once",
             "// Generated by tools/make_tables.py: edit the generator, then regenerate.",
             "#include <opxy/types.hpp>", "", "namespace thunder {", "namespace tables {"]
    # 2^(i / 256) in Q30, i = 0..256.
    e = [round(2 ** 30 * 2 ** (i / 256)) for i in range(257)]
    lines.append("// 2^(i / 256), Q30.")
    lines.append("const opxy::u32 exp2[257] = {" + ", ".join(str(v) + "u" for v in e) + "};")
    # A whole sine cycle in 1024 steps, Q15, with a guard point.
    s = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
    lines.append("// sin(2 pi i / 1024), Q15, with a guard point.")
    lines.append("const opxy::i16 sine[1025] = {" + ", ".join(map(str, s)) + "};")
    # Sheet modes.
    ratio, mm, nn = [], [], []
    for t in range(TENSIONS):
        modes = sheet_modes(t / (TENSIONS - 1))
        ratio.append([round(4096 * math.log2(r)) for r, _m, _n in modes])
        mm.append([m for _r, m, _n in modes])
        nn.append([n for _r, _m, n in modes])
    lines.append("// The sheet's eight lowest modes at 33 tensions, plate (0) to membrane (32):")
    lines.append("// log2 of each mode's frequency over the (1, 1) mode's, Q12, and its m and n.")
    lines.append("const opxy::i16 mode_ratio[33][8] = {" + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in ratio) + "};")
    lines.append("const opxy::u8 mode_m[33][8] = {" + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in mm) + "};")
    lines.append("const opxy::u8 mode_n[33][8] = {" + ", ".join("{" + ", ".join(map(str, r)) + "}" for r in nn) + "};")
    lines += ["}", "}", ""]
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
